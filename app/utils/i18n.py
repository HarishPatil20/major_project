def get_lang_code() -> str:
    return _LANG_CODE.get(st.session_state.get("app_language", "English"), "en")


def t(key: str, **kwargs) -> str:
    """Translate a UI string key into the currently selected language.

    Falls back to English, then to the raw key, if a translation is
    missing — so a missing string never breaks the page.
    """
    code = get_lang_code()
    text = TRANSLATIONS.get(code, {}).get(key) or TRANSLATIONS["en"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def language_selector(key: str = "app_language_selector"):
    """Render the language dropdown and update the shared session state.

    Returns the selected display name (e.g. "Hindi (हिंदी)").
    """
    current = st.session_state.get("app_language", "English")
    index = LANGUAGES.index(current) if current in LANGUAGES else 0
    choice = st.selectbox(
        "🌐 Language",
        LANGUAGES,
        index=index,
        key=key,
        label_visibility="collapsed",
    )
    if choice != current:
        st.session_state["app_language"] = choice
        st.rerun()
    return choice
